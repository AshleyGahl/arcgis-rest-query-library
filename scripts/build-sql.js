#!/usr/bin/env node
/**
 * Generates sql/03_vw_QueryLibrary.sql from sql-library/queryLibrary.js so the
 * T-SQL catalogue and the REST library never drift apart.
 */
import fs from 'node:fs';
import path from 'node:path';
import { config } from '../server/config.js';
import { queryLibrary, CATEGORIES } from '../sql-library/queryLibrary.js';

const out = path.join(config.root, 'sql', '03_vw_QueryLibrary.sql');
const q = (s) => `N'${String(s).replace(/'/g, "''")}'`;
const lines = [
  '-- ============================================================================',
  '-- 03  vw_QueryLibrary — the 70 analytical queries as a T-SQL catalogue.',
  '--     GENERATED by `npm run build:sql` from sql-library/queryLibrary.js. Do not edit by hand.',
  '--     Run any entry:  DECLARE @sql NVARCHAR(MAX) = (SELECT SQLText FROM dbo.vw_QueryLibrary WHERE QueryNumber = 44);',
  '--                     EXEC sp_executesql @sql;',
  '-- ============================================================================',
  'CREATE OR ALTER VIEW dbo.vw_QueryLibrary',
  'AS',
];
let first = true;
for (const cat of CATEGORIES) {
  const entries = queryLibrary.filter((e) => e.category === cat);
  lines.push(`-- ---------------------------------------------------------------- ${cat} (${entries[0].id}–${entries.at(-1).id})`);
  for (const e of entries) {
    lines.push(`${first ? '' : 'UNION ALL\n'}SELECT ${e.id} AS QueryNumber, ${q(e.category)} AS Category, ${q(e.dimension)} AS Dimension, ${q(e.layer)} AS AnalyticalLayer,`);
    lines.push(`       ${q(e.question)} AS Question,`);
    lines.push(`       ${q(e.tsql)} AS SQLText`);
    first = false;
  }
}
lines.push(';', 'GO', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${path.relative(process.cwd(), out)} (${queryLibrary.length} queries)`);
