#!/usr/bin/env node
/**
 * Generates sql/03_vw_QueryLibrary.sql from sql-library/queryLibrary.js so the
 * T-SQL catalogue and the REST library never drift apart.
 */
import fs from 'node:fs';
import path from 'node:path';
import { config } from '../server/config.js';
import { queryLibrary, CATEGORIES } from '../sql-library/queryLibrary.js';

const out = path.join(config.root, 'sql', '03_vw_QueryLibrary.sql');
const q = (s) => `N'${String(s).replace(/'/g, "''")}'`;
// A UNION resolves each column's type across all branches, but the first branch is
// all-NULL for the chart columns (Q1 is a scalar), so the NULLs are cast rather than
// left for SQL Server to type as int.
const qn = (s) => (s == null ? 'CAST(NULL AS NVARCHAR(200))' : q(s));
// ParamSpec is JSON, and wider than the chart columns: cast the NULLs to match.
const qj = (o) => (o?.length ? q(JSON.stringify(o)) : 'CAST(NULL AS NVARCHAR(1000))');
const ids = queryLibrary.map((e) => e.id);
const lines = [
  '-- ============================================================================',
  '-- 03  vw_QueryLibrary — the 30 analytical queries as a T-SQL catalogue.',
  '--     Each row carries the question, its statement, the chart contract for its result and',
  '--     the parameters it may be varied by, so one lookup tells a caller how to draw the answer',
  '--     and what a user is allowed to change about the question.',
  '--     View form:        dbo.vw_QueryLibrary        (the catalogue itself)',
  '--     Stored-proc form: dbo.usp_RunLibraryQuery    (look one up and execute it)',
  '--     GENERATED by `npm run build:sql` from sql-library/queryLibrary.js. Do not edit by hand.',
  '-- ============================================================================',
  'CREATE OR ALTER VIEW dbo.vw_QueryLibrary',
  'AS',
];
let first = true;
for (const cat of CATEGORIES) {
  const entries = queryLibrary.filter((e) => e.category === cat);
  lines.push(`-- ---------------------------------------------------------------- ${cat} (${entries[0].id}–${entries.at(-1).id})`);
  for (const e of entries) {
    lines.push(`${first ? '' : 'UNION ALL\n'}SELECT ${e.id} AS QueryNumber, ${q(e.category)} AS Category, ${q(e.dimension)} AS Dimension, ${q(e.layer)} AS AnalyticalLayer,`);
    lines.push(`       ${q(e.question)} AS Question,`);
    lines.push(`       ${e.chart ? 1 : 0} AS HasChart, ${qn(e.chart?.type)} AS ChartType, ${qn(e.chart?.labels)} AS ChartLabelColumn,`);
    lines.push(`       ${qn(e.chart?.values)} AS ChartValueColumns, ${qn(e.chart?.series)} AS ChartSeriesColumn, ${qn(e.chart?.annotation)} AS ChartAnnotationColumn,`);
    lines.push(`       ${qj(e.params)} AS ParamSpec,`);
    lines.push(`       ${q(e.tsql)} AS SQLText`);
    first = false;
  }
}
lines.push(';', 'GO', '');

// ------------------------------------------------------------------ proc form
// The catalogue's counterpart to the view: resolve a query number to its statement
// and run it, so a client needs the number only — the same contract the REST side
// gets from FeatureServer table 1.
lines.push(
  '-- ---------------------------------------------------------------- PROC FORM',
  'CREATE OR ALTER PROCEDURE dbo.usp_RunLibraryQuery',
  '    @QueryNumber INT,',
  '    @Execute     BIT = 1          -- 1 = run the statement, 0 = return it without running it',
  'AS',
  'BEGIN',
  '    SET NOCOUNT ON;',
  '',
  '    DECLARE @sql NVARCHAR(MAX), @question NVARCHAR(400);',
  '',
  '    SELECT @sql      = l.SQLText,',
  '           @question = l.Question',
  '    FROM dbo.vw_QueryLibrary AS l',
  '    WHERE l.QueryNumber = @QueryNumber;',
  '',
  '    IF @sql IS NULL',
  `        THROW 50010, N'@QueryNumber is not in dbo.vw_QueryLibrary (valid range: ${Math.min(...ids)}-${Math.max(...ids)}).', 1;`,
  '',
  '    IF @Execute = 0',
  '    BEGIN',
  '        SELECT QueryNumber = @QueryNumber, Question = @question, SQLText = @sql;',
  '        RETURN;',
  '    END',
  '',
  "    PRINT CONCAT(N'-- Q', @QueryNumber, N': ', @question);",
  '    EXEC sys.sp_executesql @stmt = @sql;',
  'END',
  'GO',
  '',
  '-- ---------------------------------------------------------------- USAGE',
  '-- Run one query:            EXEC dbo.usp_RunLibraryQuery @QueryNumber = 14;',
  '-- Inspect without running:  EXEC dbo.usp_RunLibraryQuery @QueryNumber = 14, @Execute = 0;',
  '-- Browse the catalogue:     SELECT QueryNumber, Dimension, AnalyticalLayer, Question FROM dbo.vw_QueryLibrary ORDER BY QueryNumber;',
  '-- Chart contract only:      SELECT QueryNumber, Question, ChartType, ChartLabelColumn, ChartValueColumns FROM dbo.vw_QueryLibrary WHERE HasChart = 1;',
  '-- What may be varied:       SELECT QueryNumber, Question, ParamSpec FROM dbo.vw_QueryLibrary WHERE ParamSpec IS NOT NULL;',
  '--',
  '-- A row with a ParamSpec may be run with a different value for a declared parameter, within',
  '-- the range its author ratified. The proc runs SQLText as published (the ratified default);',
  '-- binding a value means rendering the declared template over the declared `find` text, which',
  '-- the REST side does on the trusted side at /FeatureServer/1/execute. Do the same here rather',
  '-- than letting a caller pass SQL: the parameter is the only sanctioned variation.',
  '--',
  '-- From .NET / Dapper:',
  '--   var rows = await conn.QueryAsync("dbo.usp_RunLibraryQuery",',
  '--       new { QueryNumber = 14 }, commandType: CommandType.StoredProcedure);',
  '--',
  '-- Some entries assume SET DATEFIRST 7 (Sunday = 1) — see the Notes column of',
  '-- FeatureServer table 1, or the `notes` field in sql-library/queryLibrary.js.',
  '',
);
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${path.relative(process.cwd(), out)} (${queryLibrary.length} queries)`);
